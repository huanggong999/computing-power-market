CREATE TABLE IF NOT EXISTS volcano_cpu_sale_price (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '售价配置ID',
    region_code VARCHAR(64) NOT NULL,
    instance_type_id VARCHAR(128) NOT NULL,
    family VARCHAR(128) DEFAULT NULL,
    cpu_cores INT DEFAULT NULL,
    cpu_model VARCHAR(128) DEFAULT NULL,
    mem_gib DECIMAL(12,2) DEFAULT NULL,
    billing_type VARCHAR(16) NOT NULL COMMENT 'on_demand 或 monthly',
    upstream_price DECIMAL(12,4) DEFAULT NULL,
    sale_price DECIMAL(12,4) NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'CNY',
    status TINYINT(1) NOT NULL DEFAULT 1,
    remark VARCHAR(256) DEFAULT NULL,
    price_version VARCHAR(64) DEFAULT NULL,
    create_by VARCHAR(64) DEFAULT NULL,
    create_by_id BIGINT DEFAULT NULL,
    create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64) DEFAULT NULL,
    update_by_id BIGINT DEFAULT NULL,
    update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    del_flag TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_volcano_cpu_region_instance_billing (region_code, instance_type_id, billing_type),
    KEY ix_volcano_cpu_region (region_code),
    KEY ix_volcano_cpu_instance (instance_type_id),
    CONSTRAINT chk_volcano_cpu_sale_price CHECK (sale_price > 0),
    CONSTRAINT chk_volcano_cpu_billing_type CHECK (billing_type IN ('on_demand','monthly')),
    CONSTRAINT chk_volcano_cpu_status CHECK (status IN (0,1)),
    CONSTRAINT chk_volcano_cpu_del_flag CHECK (del_flag IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='火山云CPU平台售价配置';
